def seed():
    init_db()
    db = SessionLocal()
    try:
        existing = db.query(CRMProperty).count()
        if existing > 0:
            print(f"INFO: Database already contains {existing} properties. Skipping seed.")
            return

        for data in FICTIONAL_PROPERTIES:
            prop = CRMProperty(**data)
            db.add(prop)

        db.commit()
        count = db.query(CRMProperty).count()
        print(f"[OK] Seeded {count} fictional CRM properties successfully.")
    finally:
        db.close()


if __name__ == "__main__":
    seed()
